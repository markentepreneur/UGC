/**
 * Seeds quiz questions and their respective options/features into the database.
 */
export async function questionsSeed() {
  try {
    // REMOVE ALL EXISTING QUESTIONS AND OPTIONS
    await QuizOption.deleteMany({});
    await QuizQuestion.deleteMany({});

    // Prepare seed data, based on app/(client)/quiz/page.tsx

    for (const q of questions) {
      const questionDoc = await QuizQuestion.create({
        question: q.question,
        multipleChoice: q.multipleChoice,
        title: q.title,
        description: q.description,
        image: q.image, // <-- add image property on question
      });

      for (const opt of q.options) {
        await QuizOption.create({
          questionId: questionDoc._id,
          text: opt.text,
          featureTitle: opt.featureTitle,
          featureDescription: opt.featureDescription,
          featureBenefits: opt.featureBenefits,
        });
      }
    }

    console.log("✅ Quiz questions and options seeded successfully");
  } catch (err) {
    console.error("❌ Seeding quiz questions failed:", err);
    throw err;
  }
}
